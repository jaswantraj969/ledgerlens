"""llama3.2:3b against qwen3:4b as S4h on the train subset, by the 2026-11-08 pre-registered rule.

Adopt qwen3:4b only if (a) mean F1 (total, subtotal, tax, row-level) is at least 0.05 higher,
(b) its warm p95 LLM latency per document is at most twice llama's, and (c) at most one of its
runs aborted on memory. Otherwise keep llama3.2:3b. Never edited by hand.
"""

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
ROUND = ROOT / "evals" / "results" / "dev" / "prompt_round"
ABORTED = ROOT / "evals" / "results" / "aborted"
OUTPUT = ROOT / "evals" / "results" / "dev" / "model_comparison"
FILES = {
    "llama3.2:3b": ROUND / "cord_s4h_prompt_dev_train100_p2.2_v1_1_1.json",
    "qwen3:4b": ROUND / "cord_s4h-qwen_prompt_dev_train100_p2.2_v1_1_1.json",
}
ABORT_PATTERNS = {"llama3.2:3b": "cord_s4h_train_aborted_*.json",
                  "qwen3:4b": "cord_s4h-qwen_train_aborted_*.json"}  # fmt: skip
MIN_GAIN = 0.05
MAX_LATENCY_RATIO = 2.0
MAX_ABORTS = 1


def summary(model: str) -> dict[str, Any]:
    result = json.loads(FILES[model].read_text(encoding="utf-8"))
    f1 = {name: result["fields"][name]["f1"] or 0.0 for name in ("total_amount", "subtotal",
                                                                  "tax_amount")}  # fmt: skip
    f1["rows"] = result["line_items_row_level"]["f1"] or 0.0
    return {
        "model": result["llm"]["model"],
        "params": result["llm"]["params"],
        "f1": f1,
        "mean_f1": sum(f1.values()) / 4,
        "warm_llm_p95_seconds": result["latency_seconds"]["warm_llm"]["p95"],
        "warm_llm_p50_seconds": result["latency_seconds"]["warm_llm"]["p50"],
        "timings": result["latency_seconds"]["source"],
        "failed_extractions": result["failures"]["failed_extractions"],
        "pass_fallbacks": result["failures"]["pass_fallbacks"],
        "truncated_replies": result["failures"]["truncated_replies"],
        "memory_aborts": len(list(ABORTED.glob(ABORT_PATTERNS[model]))),
        "source": FILES[model].relative_to(ROOT).as_posix(),
    }


def main() -> None:
    llama, qwen = summary("llama3.2:3b"), summary("qwen3:4b")
    gain = qwen["mean_f1"] - llama["mean_f1"]
    ratio = qwen["warm_llm_p95_seconds"] / llama["warm_llm_p95_seconds"]
    checks = {
        "mean_f1_gain_at_least_0.05": gain >= MIN_GAIN,
        "warm_p95_at_most_2x": ratio <= MAX_LATENCY_RATIO,
        "at_most_one_memory_abort": qwen["memory_aborts"] <= MAX_ABORTS,
    }
    adopted = "qwen3:4b" if all(checks.values()) else "llama3.2:3b"
    payload = {"llama": llama, "qwen": qwen, "mean_f1_gain": gain, "warm_p95_ratio": ratio,
               "checks": checks, "adopted": adopted}  # fmt: skip
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "model_comparison.json").write_text(json.dumps(payload, indent=2) + "\n",
                                                  encoding="utf-8", newline="\n")  # fmt: skip
    rows = [
        f"| {s['model']} | {s['f1']['total_amount']:.3f} | {s['f1']['subtotal']:.3f} "
        f"| {s['f1']['tax_amount']:.3f} | {s['f1']['rows']:.3f} | {s['mean_f1']:.3f} "
        f"| {s['warm_llm_p50_seconds']:.2f} / {s['warm_llm_p95_seconds']:.2f} "
        f"| {s['failed_extractions']} | {s['pass_fallbacks']} | {s['memory_aborts']} |"
        for s in (llama, qwen)
    ]
    lines = [
        "# S4h on the 100-document train subset: llama3.2:3b against qwen3:4b (metrics 1.1.1)",
        "",
        "Generated by `evals/runners/make_model_comparison.py`. Do not edit by hand. Rule "
        "pre-registered in docs/evaluation.md before any qwen3 result. Validation not read.",
        "",
        "| Model | Total F1 | Subtotal F1 | Tax F1 | Row F1 | Mean | Warm LLM p50 / p95 s "
        "| Failed | Pass fallbacks | Memory aborts |",
        "|---|---|---|---|---|---|---|---|---|---|",
        *rows,
        "",
        f"- Mean F1 gain: {gain:+.3f} (needs >= {MIN_GAIN}): "
        f"{'met' if checks['mean_f1_gain_at_least_0.05'] else 'not met'}.",
        f"- Warm p95 ratio: {ratio:.2f}x (needs <= {MAX_LATENCY_RATIO}x): "
        f"{'met' if checks['warm_p95_at_most_2x'] else 'not met'}.",
        f"- qwen3 memory aborts: {qwen['memory_aborts']} (needs <= {MAX_ABORTS}): "
        f"{'met' if checks['at_most_one_memory_abort'] else 'not met'}.",
        f"- Timings: llama {llama['timings']}; qwen {qwen['timings']}.",
        "",
        f"**Adopted: {adopted}.**",
        "",
    ]
    (OUTPUT / "model_comparison.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("adopted", adopted, checks)


if __name__ == "__main__":
    main()
