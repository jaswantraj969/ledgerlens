"""Prompt round table and choice, by the rule pre-registered in docs/evaluation.md.

Score: the mean of total, subtotal, tax and row-level F1 for S2 on the train subset. The final
prompt is the best candidate (2.0, 2.1, 2.2); a tie goes to the shorter prompt, and the
candidates are listed shortest first. 1.0 is the reference and is not a candidate.
"""

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
ROUND = ROOT / "evals" / "results" / "dev" / "prompt_round"
SUBSET = "prompt_dev_train100"
CANDIDATES = ("2.0", "2.1", "2.2")  # shortest first
REFERENCE = "1.0"
FIELDS = ("total_amount", "subtotal", "tax_amount")


def load(prompt: str) -> dict[str, Any]:
    path = ROUND / f"cord_s2_{SUBSET}_p{prompt}_v1_1_1.json"
    return dict(json.loads(path.read_text(encoding="utf-8")))


def scores(result: dict[str, Any]) -> dict[str, float]:
    values = {name: result["fields"][name]["f1"] or 0.0 for name in FIELDS}
    values["rows"] = result["line_items_row_level"]["f1"] or 0.0
    values["mean"] = sum(values.values()) / 4
    return values


def choose(results: dict[str, dict[str, float]]) -> str:
    best = max(results[p]["mean"] for p in CANDIDATES)
    return next(p for p in CANDIDATES if results[p]["mean"] == best)


def main() -> None:
    loaded = {p: load(p) for p in (REFERENCE, *CANDIDATES)}
    table = {p: scores(r) for p, r in loaded.items()}
    final = choose(table)
    lines = [
        "# Prompt round 2: S2 on the 100-document CORD train subset (metrics 1.1.1)",
        "",
        "Generated by `evals/runners/make_prompt_round_table.py`. Do not edit by hand. "
        "Validation was not read for this choice.",
        "",
        "| Prompt | Role | Total F1 | Subtotal F1 | Tax F1 | Row F1 | Mean | Failed | Truncated "
        "| num_ctx | Warm LLM p50 / p95 s |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for prompt, result in loaded.items():
        s = table[prompt]
        role = (
            "reference"
            if prompt == REFERENCE
            else ("**chosen**" if prompt == final else "candidate")
        )
        warm = result["latency_seconds"]["warm_llm"]
        latency = "n/a" if not warm["n"] else f"{warm['p50']:.2f} / {warm['p95']:.2f}"
        lines.append(
            f"| {prompt} | {role} | {s['total_amount']:.3f} | {s['subtotal']:.3f} "
            f"| {s['tax_amount']:.3f} | {s['rows']:.3f} | {s['mean']:.3f} "
            f"| {result['failures']['failed_extractions']} "
            f"| {result['failures']['truncated_replies']} "
            f"| {result['llm']['params']['num_ctx']} | {latency} |"
        )
    lines += [
        "",
        f"Chosen prompt: **{final}**, by the highest mean of the four F1 values among the "
        "candidates, ties to the shorter prompt.",
        "",
    ]
    (ROUND / "prompt_round.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    (ROUND / "prompt_round.json").write_text(
        json.dumps({"scores": table, "final_prompt": final}, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print("chosen", final, {p: round(s["mean"], 3) for p, s in table.items()})


if __name__ == "__main__":
    main()
