"""A12 check: score saved predictions per pre-registered CORD layout group.

This reuses predictions from run_cord.py, so no model or OCR runs here. Groups approximate
layouts, not vendors. All groups appear in train, validation and test, so this measures how
results vary across layouts. It does not measure generalisation to unseen vendors.
"""

import argparse
import json
from pathlib import Path
from typing import Any

from evals.datasets.cord import HEADER_FIELDS, ROW_FIELDS, iter_documents
from evals.runners.run_cord_s1 import environment
from evals.scoring import DocumentPrediction, score

ROOT = Path(__file__).resolve().parents[2]
PREDICTIONS = ROOT / "data" / "cord-v2" / "predictions"
GROUPS = ROOT / "evals" / "splits" / "cord_v2" / "layout_groups.json"
RESULTS = ROOT / "evals" / "results"


def _rate(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def group_table(result: dict[str, Any]) -> str:
    lines = [
        f"# {result['system']} on CORD {result['split']} by derived layout group (metrics 1.1)",
        "",
        "Generated by `evals/runners/run_cord_groups.py`. Do not edit by hand.",
        "",
        result["statement"],
        "",
        "Groups hold few documents, so each row is noisy. Compare the spread, not single rows.",
        "",
        "| Group | Documents | Total F1 | Subtotal F1 | Tax F1 | Row-level F1 |",
        "|---|---|---|---|---|---|",
    ]
    for group, row in result["groups"].items():
        fields = row["fields"]
        lines.append(
            f"| {group} | {row['n']} | {_rate(fields['total_amount']['f1'])} "
            f"| {_rate(fields['subtotal']['f1'])} | {_rate(fields['tax_amount']['f1'])} "
            f"| {_rate(row['line_items_row_level']['f1'])} |"
        )
    spread = result["spread_for_groups_with_at_least_5_documents"]
    lines += [
        "",
        "Spread across groups with at least 5 documents:",
        "",
        "| Measure | Lowest | Highest | All documents |",
        "|---|---|---|---|",
    ]
    for name, row in spread.items():
        lines.append(
            f"| {name} | {_rate(row['lowest'])} | {_rate(row['highest'])} "
            f"| {_rate(row['overall'])} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--system", default="s1")
    parser.add_argument("--split", choices=["validation", "test"], default="test")
    arguments = parser.parse_args()

    assignments = json.loads(GROUPS.read_text(encoding="utf-8"))["assignments"]
    raw = json.loads(
        (PREDICTIONS / f"{arguments.system}_{arguments.split}.json").read_text(encoding="utf-8")
    )
    predictions = [DocumentPrediction(**item) for item in raw]
    headers: dict[str, dict[str, str | None]] = {}
    rows: dict[str, list[dict[str, str | None]]] = {}
    for document in iter_documents(arguments.split, with_images=False):  # type: ignore[arg-type]
        headers[document.document_id] = {f: document.gold[f] for f in HEADER_FIELDS}
        rows[document.document_id] = document.gold_rows

    def scored(subset: list[DocumentPrediction]) -> dict[str, Any]:
        return score(subset, headers, rows, tuple(HEADER_FIELDS), tuple(ROW_FIELDS))

    by_group: dict[int, list[DocumentPrediction]] = {}
    for prediction in predictions:
        by_group.setdefault(assignments[prediction.document_id], []).append(prediction)
    groups = {
        str(group): {"n": len(subset), **scored(subset)}
        for group, subset in sorted(by_group.items())
    }
    overall = scored(predictions)
    large = [row for row in groups.values() if row["n"] >= 5]

    def spread(pick: Any, whole: float | None) -> dict[str, float | None]:
        values = [value for value in (pick(row) for row in large) if value is not None]
        return {
            "lowest": min(values) if values else None,
            "highest": max(values) if values else None,
            "overall": whole,
        }

    result = {
        "system": arguments.system.upper(),
        "dataset": "cord-v2",
        "split": arguments.split,
        "statement": (
            "No real vendor-grouped split was possible: CORD has no vendor label, and SROIE is "
            "blocked. These are derived layout groups, fitted on train word positions. Every "
            "group appears in train, validation and test, and S1 has no fitted parameters, so "
            "this shows variation across layouts, not generalisation to unseen vendors."
        ),
        "metrics_version": overall["metrics_version"],
        "groups": groups,
        "spread_for_groups_with_at_least_5_documents": {
            "total_amount_f1": spread(
                lambda row: row["fields"]["total_amount"]["f1"],
                overall["fields"]["total_amount"]["f1"],
            ),
            "subtotal_f1": spread(
                lambda row: row["fields"]["subtotal"]["f1"], overall["fields"]["subtotal"]["f1"]
            ),
            "row_level_f1": spread(
                lambda row: row["line_items_row_level"]["f1"], overall["line_items_row_level"]["f1"]
            ),
        },
        "environment": environment(),
    }
    suffix = "" if arguments.split == "test" else "_validation"
    output = RESULTS / f"cord_{arguments.system}{suffix}_v1_1_layout_groups.json"
    output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n")
    output.with_suffix(".md").write_text(group_table(result), encoding="utf-8", newline="\n")
    print("wrote", output)


if __name__ == "__main__":
    main()
