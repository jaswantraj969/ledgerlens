"""Final test tables and figure, from saved result files only. Never edited by hand.

Reads the files fixed in docs/evaluation/final-test-protocol.md and writes evals/results/final/:
the S1-S4h test comparison, the S5 test table, the S5 ablation table, the degradation table and
the degradation figure. No model is called and no dataset file is read. A missing input is
reported as missing, never filled.

    python -m evals.runners.make_final_tables
"""

import json
from pathlib import Path
from typing import Any

from evals.runners import make_s5_table, make_validation_comparison

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "evals" / "results"
FINAL = RESULTS / "final"
DEGRADATION = RESULTS / "degradation"
CONDITIONS = (
    ("clean", "Clean"),
    ("blur-1.5", "Blur 1.5"),
    ("blur-3.0", "Blur 3.0"),
    ("jpeg-30", "JPEG 30"),
    ("jpeg-10", "JPEG 10"),
)
DEGRADED_SYSTEMS = (("s1", "S1"), ("s4h", "S4h"))
FIELDS = (("total_amount", "Total"), ("subtotal", "Subtotal"), ("tax_amount", "Tax"))
# Reference palette, categorical slots 1 and 2, validated with the dataviz skill's validator.
SERIES_COLORS = {"S1": "#2a78d6", "S4h": "#eb6834"}
SERIES_MARKERS = {"S1": "o", "S4h": "s"}
SURFACE, INK, INK_SECONDARY, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e1e0d9"


def _num(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _ci(value: float | None, interval: list[float] | None) -> str:
    if value is None:
        return "n/a"
    return f"{value:.3f} [{interval[0]:.3f}, {interval[1]:.3f}]" if interval else f"{value:.3f}"


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def mean_f1(result: dict[str, Any]) -> float:
    values = [result["fields"][key]["f1"] or 0.0 for key, _ in FIELDS]
    values.append(result["line_items_row_level"]["f1"] or 0.0)
    return sum(values) / 4


def degradation_path(system: str, condition: str) -> Path:
    if condition == "clean":
        return RESULTS / f"cord_{system}_v1_1_1.json"
    return DEGRADATION / f"cord_{system}_{condition}_v1_1_1.json"


def degradation_table() -> dict[str, dict[str, float | None]]:
    lines = [
        "# Degradation on CORD test (metrics 1.1.1)",
        "",
        "Generated by `evals/runners/make_final_tables.py`. Do not edit by hand. The 100 test "
        "images, each perturbed once by a fixed, deterministic transform (evals/perturb.py), then "
        "OCR and extraction as in the clean run. Clean rows are the final clean test reads.",
        "",
        "| System | Condition | Total F1 [95% CI] | Subtotal F1 [95% CI] | Tax F1 [95% CI] "
        "| Row F1 [95% CI] | Mean of four F1 | Change in mean vs clean | Failed | Truncated "
        "| Power |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    means: dict[str, dict[str, float | None]] = {}
    for system, label in DEGRADED_SYSTEMS:
        means[label] = {}
        clean = _load(degradation_path(system, "clean"))
        for condition, name in CONDITIONS:
            result = _load(degradation_path(system, condition))
            if result is None:
                means[label][condition] = None
                lines.append(f"| {label} | {name} | missing |  |  |  |  |  |  |  |  |")
                continue
            mean = mean_f1(result)
            means[label][condition] = mean
            change = ""
            if condition != "clean" and clean is not None:
                change = f"{mean - mean_f1(clean):+.3f}"
            fields = " | ".join(
                _ci(result["fields"][key]["f1"], result["fields"][key]["f1_ci95"])
                for key, _ in FIELDS
            )
            rows = result["line_items_row_level"]
            lines.append(
                f"| {label} | {name} | {fields} | {_ci(rows['f1'], rows['f1_ci95'])} "
                f"| {mean:.3f} | {change} | {result['failures']['failed_extractions']} "
                f"| {result['failures'].get('truncated_replies', 0)} "
                f"| {(result.get('power') or {}).get('label', 'not recorded')} |"
            )
    lines += [
        "",
        "Severities: Gaussian blur with radius (standard deviation) 1.5 and 3.0 pixels; JPEG "
        "re-encoding at quality 30 and 10. Mean of four F1: total, subtotal, tax and row-level.",
        "",
    ]
    (FINAL / "cord_degradation_test_v1_1_1.md").write_text(
        "\n".join(lines), encoding="utf-8", newline="\n"
    )
    return means


def degradation_figure(means: dict[str, dict[str, float | None]]) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    figure, axis = plt.subplots(figsize=(7.2, 4.0), dpi=150)
    figure.patch.set_facecolor(SURFACE)
    axis.set_facecolor(SURFACE)
    positions = list(range(len(CONDITIONS)))
    for label, values in means.items():
        points = [(x, values[c]) for x, (c, _) in zip(positions, CONDITIONS, strict=True)]
        points = [(x, y) for x, y in points if y is not None]
        if not points:
            continue
        xs, ys = zip(*points, strict=True)
        style = {"color": SERIES_COLORS[label], "marker": SERIES_MARKERS[label]}
        axis.plot(xs, ys, linewidth=2, markersize=8, markeredgecolor=SURFACE,
                  markeredgewidth=2, label=label, **style)  # fmt: skip
        axis.annotate(label, (xs[-1], ys[-1]), xytext=(8, 0), textcoords="offset points",
                      va="center", color=INK, fontsize=9)  # fmt: skip
    axis.set_xticks(positions, [name for _, name in CONDITIONS], color=INK_SECONDARY, fontsize=9)
    axis.set_ylim(0, 1)
    axis.set_ylabel("Mean of four F1", color=INK_SECONDARY, fontsize=9)
    axis.tick_params(axis="y", colors=INK_SECONDARY, labelsize=9)
    axis.tick_params(axis="x", length=0)
    axis.grid(axis="y", color=GRID, linewidth=0.8)
    axis.set_axisbelow(True)
    for side in ("top", "right", "left"):
        axis.spines[side].set_visible(False)
    axis.spines["bottom"].set_color(GRID)
    axis.set_title("Mean F1 on CORD test under image degradation", color=INK, fontsize=11,
                   loc="left")  # fmt: skip
    axis.legend(frameon=False, fontsize=9, loc="lower left", labelcolor=INK)
    figure.tight_layout()
    figure.savefig(FINAL / "cord_degradation_test_v1_1_1.png", facecolor=SURFACE)
    plt.close(figure)


def ablation_table() -> None:
    lines = [
        "# S5 ablations on CORD test (metrics 1.1.1)",
        "",
        "Generated by `evals/runners/make_final_tables.py`. Do not edit by hand. Each ablation "
        "refits the calibrators on train with one signal family removed (or with an isotonic "
        "calibrator), chooses thresholds on validation, and is scored once on test. No model "
        "calls. Variant: all. Change: test automation minus the full model's.",
        "",
        "| Base | Ablation | Units | Target | Threshold | Test automation [95% CI] "
        "| Test achieved precision [95% CI] | Target met | Change in automation | ROC-AUC | ECE "
        "| Columns removed |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    result = _load(RESULTS / "cord_s5_ablations_v1_1_1.json")
    if result is None:
        lines.append("| missing |  |  |  |  |  |  |  |  |  |  |  |")
    else:
        for base, block in result["bases"].items():
            full = block["ablations"]["full"]["test"]
            for name, entry in block["ablations"].items():
                for kind in ("header", "row"):
                    report = entry["test"][kind]
                    removed = len(entry["removed_columns_present_in_train"][kind])
                    for target, values in report["targets"].items():
                        reference = full[kind]["targets"][target]["automation_rate"]
                        automation = values["automation_rate"]
                        change = "" if name == "full" else f"{automation - reference:+.3f}"
                        precision = _ci(
                            values["achieved_precision"], values["achieved_precision_ci95"]
                        )
                        lines.append(
                            f"| {base} | {name} | {kind} | {target} | {_num(values['threshold'])} "
                            f"| {_ci(automation, values['automation_rate_ci95'])} "
                            f"| {precision} "
                            f"| {'yes' if values['target_met'] else 'no'} | {change} "
                            f"| {_num(report['roc_auc'])} | {_num(report['ece_10_bins'])} "
                            f"| {removed} |"
                        )
    lines += [
        "",
        "Row units carry only evidence and rule-check features, so an ablation of a family they "
        "lack removes no row columns (0 in the last column) and leaves the row model unchanged.",
        "",
    ]
    (FINAL / "cord_s5_ablations_test_v1_1_1.md").write_text(
        "\n".join(lines), encoding="utf-8", newline="\n"
    )


def main() -> None:
    FINAL.mkdir(parents=True, exist_ok=True)
    make_validation_comparison.main(["--split", "test"])
    make_s5_table.main(["--final", "s1", "s4h"])
    ablation_table()
    means = degradation_table()
    degradation_figure(means)
    print("wrote", FINAL)


if __name__ == "__main__":
    main()
